const { chromium } = require('playwright');
const R = process.argv[2];
let fails = 0;
const check = (name, ok, extra) => { console.log((ok ? 'PASS ' : 'FAIL ') + name + (!ok && extra !== undefined ? '  -> ' + String(extra).slice(0, 400) : '')); if (!ok) fails++; };
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ bypassCSP: true, ignoreHTTPSErrors: true, httpCredentials: { username: 'tester', password: 'test-password-1234' }, viewport: { width: 1100, height: 1100 }, permissions: ['clipboard-read', 'clipboard-write'] });
  const p = await ctx.newPage(); p.on('pageerror', e => { console.log('PAGEERROR', e.message); fails++; });
  await p.goto('https://127.0.0.1:18443/#/dupes'); await p.waitForSelector('.group');
  const panelBtn = p.locator('.sug-panel > button');
  check('the Duplicates page offers a Suggested rules panel for the 2 groups waiting', (await panelBtn.textContent()).includes('2 groups'), await panelBtn.textContent());
  check('suggested-rules.txt is linked', await p.locator('.sug-panel a[href="/out/suggested-rules.txt"]').count() === 1);
  await panelBtn.click();
  const rows = p.locator('.sug-group');
  check('both groups are listed in the panel', await rows.count() === 2, await rows.count());
  const shared = rows.filter({ hasText: 'Shared Song' });
  const odd = rows.filter({ hasText: 'Odd Length' });
  check('the far-apart pair offers only one option (plus undecided)', await odd.locator('input[type=radio]').count() === 2, await odd.locator('input[type=radio]').count());
  check('the label-mismatch group offers keep both, treat as duplicates and keep the other copy (plus undecided)', await shared.locator('input[type=radio]').count() === 4, await shared.locator('input[type=radio]').count());
  await p.locator('.sug-panel').getByRole('button', { name: 'Copy ticked lines' }).click(); await p.waitForTimeout(300);
  check('copying with nothing ticked says so and copies nothing', (await p.textContent('#toast')).includes('Nothing ticked'));
  await shared.locator('label.sug-pick', { hasText: 'Keep this copy instead' }).locator('input').check();
  await odd.locator('label.sug-pick', { hasText: 'Keep every copy' }).locator('input').check();
  check('the counter follows the ticks', (await p.textContent('.sug-panel .toolbar')).includes('2 group(s) ticked'));
  await shared.locator('label.sug-pick', { hasText: 'Keep every copy' }).locator('input').check();
  check('ticking another option for the same song replaces the first', (await p.textContent('.sug-panel .toolbar')).includes('2 group(s) ticked'));
  await shared.locator('label.sug-pick', { hasText: 'Keep this copy instead' }).locator('input').check();
  await p.locator('.sug-panel').getByRole('button', { name: 'Copy ticked lines' }).click(); await p.waitForTimeout(300);
  const clip = await p.evaluate(() => navigator.clipboard.readText());
  const want = ['keep-file: Test Artist/Compilation Hits (Explicit Version) (1998)/02 - Shared Song.flac', 'dedupe-labels: Test Artist | Shared Song'];
  check('the copied block holds the keep-file and dedupe-labels lines and one keep-both-id, nothing else', want.every(l => clip.includes(l)) && /keep-both-id: [0-9a-f]{8}/.test(clip) && clip.trim().split('\n').length === 3 && !clip.includes('#'), clip);
  await p.screenshot({ path: R + '/s_suggest_panel.png' });
  await p.click('.sug-panel >> text=clear ticks');
  check('clear ticks empties the selection', (await p.textContent('.sug-panel .toolbar')).includes('0 group(s) ticked'));
  // per-group button on the card
  const card = p.locator('.group', { hasText: 'Shared Song' });
  await card.locator('.group-head').click(); await card.locator('.member').first().waitFor();
  await card.getByRole('button', { name: 'Suggested rules' }).click();
  const box = card.locator('.sug');
  check('the card shows why it is held and the options', (await box.textContent()).includes('label differs') && await box.locator('.sug-row').count() === 3, await box.textContent());
  await box.locator('.sug-row').nth(2).getByRole('button', { name: 'copy lines' }).click(); await p.waitForTimeout(300);
  const clip2 = await p.evaluate(() => navigator.clipboard.readText());
  check('copy lines on the card copies that option\'s rule lines', clip2.trim() === want.join('\n'), clip2);
  await card.scrollIntoViewIfNeeded(); await p.screenshot({ path: R + '/s_suggest_card.png' });
  const odd2 = p.locator('.group', { hasText: 'Odd Length' });
  await odd2.locator('.group-head').click(); await odd2.locator('.member').first().waitFor();
  await odd2.getByRole('button', { name: 'Suggested rules' }).click();
  check('the far-apart pair explains why only keep-both applies', (await odd2.locator('.sug').textContent()).includes('wide-tolerance'));
  await b.close();
  console.log('FAILS: ' + fails); process.exit(fails ? 1 : 0);
})();

const { chromium } = require('playwright');
const cp = require('child_process');
const R = process.argv[2];
const code = () => cp.execSync(`python3 -c "import importlib.util,time;s=importlib.util.spec_from_file_location('r','${process.env.DEWEY_REPO}/runner.py');m=importlib.util.module_from_spec(s);s.loader.exec_module(m);print(m.totp_code(open('${R}/state/totp.key').read().strip(),int(time.time()//30)))"`).toString().trim();
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ ignoreHTTPSErrors: true, httpCredentials: { username: 'tester', password: 'test-password-1234' }, viewport: { width: 1100, height: 1000 } });
  const p = await ctx.newPage(); p.on('pageerror', e => console.log('PAGEERROR', e.message)); p.on('console', m => { if (m.type() === 'error') console.log('CONSOLE', m.text()); });
  await p.goto('https://127.0.0.1:18443/#/run'); await p.waitForSelector('.armbox');
  await p.fill('.armcode', code()); await p.click('.armbox .btn.primary'); await p.waitForSelector('.armbox.on', { timeout: 8000 });
  const card = p.locator('#cmd-apply');
  await card.scrollIntoViewIfNeeded();
  console.log('real block before dry run:', (await card.locator('.real').textContent()).slice(0, 160), '| disabled:', await card.locator('.real .btn.danger').isDisabled());
  await card.getByRole('button', { name: 'Run dry run' }).click();
  await p.waitForSelector('.console-head', { timeout: 8000 });
  await p.waitForFunction(() => document.querySelector('.console .after') && !document.querySelector('.console .after').hidden, null, { timeout: 20000 });
  await p.goto('https://127.0.0.1:18443/#/run?cmd=apply'); await p.reload(); await p.waitForSelector('#cmd-apply .real');
  const real = p.locator('#cmd-apply .real');
  console.log('real text:', (await real.textContent()).slice(0, 520));
  console.log('placeholder:', await real.locator('input[type=text]').getAttribute('placeholder'), '| password box present:', await real.locator('input[type=password]').count());
  await p.locator('#cmd-apply').scrollIntoViewIfNeeded();
  await p.screenshot({ path: R + '/s_apply_ready.png' });
  await real.locator('input[type=text]').fill('QUARANTINE'); await real.locator('.btn.danger').click();
  await p.waitForTimeout(400); console.log('toast wrong phrase:', await p.textContent('#toast'));
  await real.locator('input[type=text]').fill('QUARANTINE 3'); await real.locator('.btn.danger').click();
  await p.waitForSelector('.console-head', { timeout: 8000 });
  await p.waitForFunction(() => document.querySelector('.console .after') && !document.querySelector('.console .after').hidden, null, { timeout: 20000 });
  console.log('console:', (await p.textContent('.console pre')).slice(0, 420).replace(/\n/g, ' | '));
  console.log('head:', (await p.textContent('.console-head')).slice(0, 160));
  await p.screenshot({ path: R + '/s_apply_ran.png' });
  await b.close();
})();
